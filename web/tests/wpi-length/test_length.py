import os
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, **({'executable_path': os.environ['CHROMIUM_PATH']} if os.environ.get('CHROMIUM_PATH') else {}))
    page = browser.new_page()
    page.goto('http://localhost:5187/', wait_until='networkidle')
    page.locator('select.type').first.select_option('auto')
    page.locator('select.type').first.select_option('px')
    field = page.locator('#length')
    expect(field).to_have_value('0')
    field.fill('')
    expect(field).to_be_focused()
    expect(page.locator('select.type').first).to_have_value('px')
    field.fill('25')
    expect(page.locator('#length-output')).to_have_text('25px')
    field.fill('')
    page.get_by_text('Outside').click()
    expect(page.locator('#length-output')).to_have_text('unset')
    expect(page.locator('select.type').first).to_have_value('value')
    field = page.locator('#length')
    field.fill('12.5')
    expect(page.locator('#length-output')).to_have_text('12.5')
    page.locator('select.type').first.select_option('px')
    expect(page.locator('#length-output')).to_have_text('12.5px')
    page.locator('select.type').first.select_option('value')
    expect(page.locator('#length-output')).to_have_text('12.5')
    width = page.locator('[data-property="width"]')
    expect(width.locator('button.reset')).to_have_count(0)
    expect(page.locator('[data-property="label"] button.reset')).to_have_count(1)
    width.locator('select').select_option('default')
    expect(page.locator('#attributes')).not_to_contain_text('"width"')
    default = page.locator('[data-property="editor_options.defaultValue"]')
    expect(default).to_be_visible()
    default.locator('input').fill('42')
    expect(page.locator('#attributes')).to_contain_text('\"defaultValue\":\"42\"')
    expect(page.locator('#attributes')).to_contain_text('\"keywords\":[\"auto\"]')
    default.locator('select').select_option('px')
    expect(page.locator('#attributes')).to_contain_text('\"defaultValue\":\"42px\"')
    browser.close()
