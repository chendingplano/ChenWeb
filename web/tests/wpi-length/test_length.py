import os
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, **({'executable_path': os.environ['CHROMIUM_PATH']} if os.environ.get('CHROMIUM_PATH') else {}))
    page = browser.new_page()
    page.goto('http://localhost:5187/', wait_until='networkidle')
    length_type = page.locator('select.type').first
    expect(length_type.locator('option[value=none]')).to_have_count(1)
    length_type.select_option('none')
    expect(page.locator('#length-output')).to_have_text('none')
    page.locator('select.type').first.select_option('auto')
    page.locator('select.type').first.select_option('px')
    field = page.locator('#length')
    expect(field).to_have_value('0')
    field.fill('')
    expect(field).to_be_focused()
    expect(page.locator('select.type').first).to_have_value('px')
    field.fill('25')
    expect(page.locator('#length-output')).to_have_text('25px')
    field.fill('')
    page.get_by_text('Outside').click()
    expect(page.locator('#length-output')).to_have_text('unset')
    expect(page.locator('select.type').first).to_have_value('value')
    field = page.locator('#length')
    field.fill('12.5')
    expect(page.locator('#length-output')).to_have_text('12.5')
    page.locator('select.type').first.select_option('px')
    expect(page.locator('#length-output')).to_have_text('12.5px')
    page.locator('select.type').first.select_option('value')
    expect(page.locator('#length-output')).to_have_text('12.5')
    width = page.locator('[data-property="width"]')
    expect(width.locator('button.reset')).to_have_count(0)
    expect(page.locator('[data-property="label"] button.reset')).to_have_count(1)
    width.locator('select').select_option('default')
    expect(page.locator('#attributes')).not_to_contain_text('"width"')
    default = page.locator('[data-property="editor_options.defaultValue"]')
    expect(default).to_be_visible()
    default.locator('input').fill('42')
    expect(page.locator('#attributes')).to_contain_text('\"defaultValue\":\"42\"')
    expect(page.locator('#attributes')).to_contain_text('\"keywords\":[\"auto\"]')
    default.locator('select').select_option('px')
    expect(page.locator('#attributes')).to_contain_text('\"defaultValue\":\"42px\"')
    display = page.locator('[data-property="editor_options.displayType"] input')
    display_row = page.locator('[data-property="editor_options.displayType"]')
    default_row = page.locator('[data-property="editor_options.defaultValue"]')
    toggle_box = display_row.locator('.editor')
    default_input = default_row.locator('input')
    toggle_rect = toggle_box.bounding_box()
    default_rect = default_input.bounding_box()
    assert abs(toggle_rect['x'] - default_rect['x']) < 1
    assert abs(display_row.locator('label').bounding_box()['y'] - toggle_rect['y']) < toggle_rect['height']
    assert toggle_box.evaluate('(el) => getComputedStyle(el).backgroundColor') == default_input.evaluate('(el) => getComputedStyle(el).backgroundColor')
    help_button = display_row.locator('.help-tip button')
    expect(help_button).to_have_attribute('aria-label', '选项')
    assert help_button.bounding_box()['width'] == 5
    help_button.click()
    display_row.get_by_role('menuitem', name='帮助提示').click()
    expect(display_row.locator('[role=tooltip]')).to_be_visible()
    expect(display_row.locator('[role=tooltip]')).not_to_be_empty()
    page.keyboard.press('Escape')
    expect(display_row.get_by_role('menu')).to_have_count(0)
    expect(display).not_to_be_checked()
    page_length = page.locator('#page-length')
    expect(page_length.locator('select.type')).to_have_count(0)
    expect(page.locator('#page-length-value')).to_have_value('300px')
    page.locator('#page-length-value').fill('450px')
    expect(page.locator('#page-value')).to_have_text('450px')
    display.check()
    expect(page.locator('#attributes')).to_contain_text('"displayType":true')
    expect(page_length.locator('select.type')).to_have_value('px')
    display.uncheck()
    expect(page_length.locator('select.type')).to_have_count(0)
    expect(page.locator('#page-length-value')).to_have_value('450px')
    browser.close()
