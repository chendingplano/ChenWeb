from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page()
    page.goto('http://127.0.0.1:5198/', wait_until='networkidle')
    result = page.locator('#result')
    field = page.locator('#field')
    field.fill(''); expect(result).to_have_text('null')
    page.get_by_role('checkbox').uncheck()
    field.fill('x'); field.fill(''); expect(result).to_have_text('""')
    field.fill('Hello')
    page.locator('.mode-menu summary').click()
    page.locator('.mode-items button').nth(1).click()
    expect(result).to_have_text('{"zh-cn":"Hello"}')
    page.locator('#field').fill('你好')
    expect(result).to_have_text('{"zh-cn":"Hello","en":"你好"}')
    def dismiss(dialog): dialog.dismiss()
    page.on('dialog', dismiss)
    page.locator('.mode-menu summary').click()
    page.locator('.mode-items button').nth(2).click()
    expect(result).to_have_text('{"zh-cn":"Hello","en":"你好"}')
    page.remove_listener('dialog', dismiss)
    page.on('dialog', lambda dialog: dialog.accept())
    page.locator('.mode-items button').nth(2).click()
    expect(result).to_have_text('"Hello"')
    page.locator('#field').select_option('choice-1')
    expect(result).to_have_text('"blue"')
    page.locator('.string-menu > button').click()
    page.locator('.string-menu-items button').nth(3).click()
    page.locator('[data-group="validators"] button[aria-expanded]').click()
    page.locator('[data-group="validators"] select').select_option('string')
    assert '"validator":"string"' in page.locator('#attrs').inner_text()
    browser.close()
