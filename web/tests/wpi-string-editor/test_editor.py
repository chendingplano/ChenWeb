from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page()
    page.goto('http://127.0.0.1:5198/', wait_until='networkidle')
    result = page.locator('#result')
    field = page.locator('#field')
    field.fill(''); expect(result).to_have_text('null')
    page.get_by_role('checkbox').uncheck()
    field.fill('x'); field.fill(''); expect(result).to_have_text('""')
    field.fill('Hello')
    page.locator('#standalone .mode-menu summary').click()
    page.locator('#standalone .mode-items button').nth(1).click()
    expect(result).to_have_text('{"zh-cn":"Hello"}')
    page.locator('#field').fill('你好')
    expect(result).to_have_text('{"zh-cn":"Hello","en":"你好"}')
    def dismiss(dialog): dialog.dismiss()
    page.on('dialog', dismiss)
    page.locator('#standalone .mode-menu summary').click()
    page.locator('#standalone .mode-items button').nth(2).click()
    expect(result).to_have_text('{"zh-cn":"Hello","en":"你好"}')
    page.remove_listener('dialog', dismiss)
    page.on('dialog', lambda dialog: dialog.accept())
    page.locator('#standalone .mode-items button').nth(2).click()
    expect(result).to_have_text('"Hello"')
    page.locator('#field').select_option('choice-1')
    expect(result).to_have_text('"blue"')
    page.locator('.string-menu > button').click()
    page.locator('.string-menu-items button').nth(3).click()
    page.locator('[data-group="validators"] button[aria-expanded]').click()
    page.locator('[data-group="validators"] select').select_option('string')
    assert '"validator":"string"' in page.locator('#attrs').inner_text()
    # The Label property: the menu follows its caption, one row per language,
    # and the fields end where the other value editors end.
    prop = page.locator('[data-property="label"]')
    expect(prop.locator('.editor .mode-menu')).to_have_count(0)
    prop.locator('.heading .mode-menu summary').click()
    prop.locator('.mode-items button').nth(1).click()
    caption = prop.locator('.heading label').bounding_box()
    summary = prop.locator('.heading .mode-menu summary').bounding_box()
    gap = summary['x'] - (caption['x'] + caption['width'])
    assert 0 <= gap < 12 and abs(summary['y'] + summary['height'] / 2 - (caption['y'] + caption['height'] / 2)) < 3, (caption, summary)
    fields = [prop.locator('#test-label'), prop.locator('#test-label-zh-cn')]
    names = prop.locator('label.language')
    assert names.all_inner_texts() == ['English', 'Chinese'] or names.all_inner_texts() == ['英文', '中文']
    other = page.locator('#test-data_binding').bounding_box()
    for index, field in enumerate(fields):
        name, box = names.nth(index).bounding_box(), field.bounding_box()
        assert box['y'] <= name['y'] + name['height'] / 2 <= box['y'] + box['height'], (name, box)
        assert name['x'] + name['width'] <= box['x'], (name, box)
        assert abs(box['x'] + box['width'] - (other['x'] + other['width'])) < 1, (box, other)
    assert fields[1].bounding_box()['y'] >= fields[0].bounding_box()['y'] + fields[0].bounding_box()['height']
    fields[0].fill('Hello')
    assert '"label":{"en":"Hello"}' in page.locator('#attrs').inner_text()
    prop.locator('.heading .mode-menu summary').click()
    prop.locator('.mode-items button').nth(0).click()
    assert '"label":"Hello"' in page.locator('#attrs').inner_text()
    single = prop.locator('#test-label').bounding_box()
    assert abs(single['x'] + single['width'] - (other['x'] + other['width'])) < 1, (single, other)
    browser.close()
