#!/usr/bin/env python3
"""Generate Go prompt defaults from the active doc-processor prompt config."""

import argparse
import json
import os
import pathlib
import subprocess
import tomllib


ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED = ROOT / "server/api/doc-processing/prompt_defaults_generated.go"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--refs-out", required=True)
    args = parser.parse_args()

    local_config = ROOT / "mise.local.toml"
    configured = tomllib.loads(local_config.read_text()).get("env", {}) if local_config.exists() else {}
    prompt_dir = pathlib.Path(os.environ.get("PROMPT_DIR", configured.get("PROMPT_DIR", str(ROOT / "prompts"))))
    rows: list[tuple[str, str, str]] = []
    keys = set(configured) | {key for key in os.environ if key.endswith("_PROMPT")}
    for key in sorted(keys):
        if not key.endswith("_PROMPT") or key.startswith("REVIEW_"):
            continue
        configured_ref = configured.get(key, "")
        ref = os.environ.get(key, str(configured_ref)).strip()
        if not ref or "\n" in ref:
            continue
        path = pathlib.Path(ref)
        if not path.is_absolute():
            path = prompt_dir / path
        if path.is_file():
            rows.append((key, ref, path.read_text()))

    lines = [
        "// Code generated by scripts/generate-doc-processor-prompt-defaults.py; DO NOT EDIT.",
        "package docprocessing",
        "",
        "type embeddedPromptDefault struct { Ref string; Text string }",
        "",
        "var embeddedPromptDefaults = map[string]embeddedPromptDefault{",
    ]
    for key, ref, text in rows:
        lines.append(f"\t{json.dumps(key)}: {{Ref: {json.dumps(ref, ensure_ascii=False)}, Text: {json.dumps(text, ensure_ascii=False)} }},")
    lines.append("}")
    GENERATED.write_text("\n".join(lines) + "\n")
    subprocess.run(["gofmt", "-w", str(GENERATED)], check=True)

    refs = sorted({pathlib.Path(ref).name for _, ref, _ in rows})
    pathlib.Path(args.refs_out).write_text("\n".join(refs) + ("\n" if refs else ""))
    print(f"==> embedded {len(rows)} configured doc-processor prompt defaults")


if __name__ == "__main__":
    main()
